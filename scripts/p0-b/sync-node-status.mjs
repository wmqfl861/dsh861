/** Generate the handoff view from node state records; never grant approval. */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const readJson = path => JSON.parse(readFileSync(path, 'utf8'))
const cell = value => String(value).replaceAll('|', '&#124;').replace(/[\r\n]+/g, ' ')

/** Render a deterministic handoff view. Historical approval is not current-tree certification. */
export function renderStatus(currentNode, states) {
  const active = states.find(state => state.node === currentNode)
  if (!active || states.filter(state => state.node === currentNode).length !== 1) throw new Error('Invalid active node.')
  if (new Set(states.map(state => state.node)).size !== states.length) throw new Error('Duplicate node.')
  for (const state of states) {
    if (!/^P[0-9]+-[A-Z][A-Z0-9-]*$/.test(state.node) || !Array.isArray(state.product_acceptance_completed)
      || typeof state.next_node_allowed !== 'boolean') throw new Error('Invalid node state.')
    if (state.next_node_allowed && (state.status !== 'approved' || !state.candidate
      || !state.hard_review || !/^[0-9a-f]{64}$/.test(state.candidate_sha256))) {
      throw new Error('Admission flag lacks candidate-bound approval metadata.')
    }
  }
  const rows = [...states].sort((a, b) => a.node.localeCompare(b.node)).map(state =>
    `| ${state.node} | ${cell(state.status)} | ${cell(state.plan_version)} | ${state.hard_review ? `[历史回执](nodes/${state.node}/${state.hard_review})` : '无'} | ${state.product_acceptance_completed.length === 0 ? '无' : cell(state.product_acceptance_completed.join(', '))} |`)
  return [
    '# 节点执行状态', '',
    '<!-- Generated by scripts/p0-b/sync-node-status.mjs; do not edit this view manually. -->', '',
    '本页由 `CURRENT_NODE.json` 与 `nodes/*/state.json` 生成；不授予批准，也不替代候选绑定的真实硬审核。', '',
    `当前节点：**${currentNode}**。当前详细计划：**${cell(active.plan_version)}**。`, '',
    '| 节点 | 状态记录 | 计划版本 | 硬审核 | 已完成产品 AC |',
    '|---|---|---|---|---|', ...rows, '',
    '历史 approved/PASS 仅对应当时的固定候选，不认证后来提交的整个工作树。', '',
    `当前活动：${cell(active.current_activity)}`, '',
    `当前阻塞：${cell(active.blocker ?? '无已登记阻塞')}`, '',
    `下一节点准入记录：**${active.next_node_allowed ? '已记录允许；执行前仍须核验候选及硬审核' : '不允许'}**。`, '',
    '## 接手入口', '',
    `当前状态：[${currentNode}/state.json](nodes/${currentNode}/state.json)。`, '',
    '本轮整改：[范围、证据和未完成事项](remediation/2026-09-09/README.md)。', '',
    'P0-B 后继计划请求：[plan-revision-request.r01.md](nodes/P0-B/plan-revision-request.r01.md)。旧计划保持原样，本请求不是 Codex 计划。', '',
    '映射纠正：[acceptance-map.r01.json](nodes/P0-B/acceptance-map.r01.json)。局部验证不等于产品 AC 全部通过。', '',
    '规则：[节点开发与硬审核](../NODE_DEVELOPMENT_RULES.md)。需求：[主规格](../MULTI_AGENT_REQUIREMENTS.md)。', '',
    '## 更新与检查', '',
    '```sh',
    'node scripts/p0-b/sync-node-status.mjs --write',
    'node scripts/p0-b/sync-node-status.mjs --check',
    '```', '',
    '修改权威状态后重新生成本页；检查模式发现漂移返回非零，不自动更改节点状态。', '',
  ].join('\n')
}

function main() {
  const args = process.argv.slice(2)
  if (args.length !== 1 || !['--check', '--write'].includes(args[0])) throw new Error('Use --check or --write from repository root.')
  const root = process.cwd()
  const current = readJson(join(root, 'development/CURRENT_NODE.json')).node
  const nodes = join(root, 'development/nodes')
  const states = readdirSync(nodes, { withFileTypes: true }).filter(entry => entry.isDirectory())
    .map(entry => {
      const state = readJson(join(nodes, entry.name, 'state.json'))
      if (state.node !== entry.name) throw new Error('Node identity does not match directory.')
      return state
    })
  const generated = renderStatus(current, states)
  const target = join(root, 'development/NODE_STATUS.md')
  if (args[0] === '--write') writeFileSync(target, generated)
  else if (readFileSync(target, 'utf8') !== generated) throw new Error('NODE_STATUS.md is stale; regenerate it.')
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { main() } catch { console.error('Node-status check failed: invalid state or stale generated view.'); process.exitCode = 1 }
}
